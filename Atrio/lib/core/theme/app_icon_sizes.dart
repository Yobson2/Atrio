/// Icon size tokens for the design system.
///
/// Use these constants for all icon sizing throughout the app.
class AppIconSizes {
  const AppIconSizes._();

  /// 14px – inline metadata icons (location pin, calendar).
  static const double xs = 14;

  /// 16px – chip and badge icons.
  static const double sm = 16;

  /// 20px – button leading icons, list tile icons.
  static const double md = 20;

  /// 24px – standard Material icon size.
  static const double lg = 24;

  /// 32px – section header icons.
  static const double xl = 32;

  /// 48px – empty state / placeholder icons.
  static const double xxl = 48;

  /// 64px – onboarding illustrations, large empty states.
  static const double hero = 64;
}
